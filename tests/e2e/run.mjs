// End-to-end check against the REAL dsh stack (DSH itself is not mocked):
//
//   1. start a local OpenAI-compatible upstream that records every request;
//   2. boot `dsh --profile headless` with an overlay that routes a `gwds`
//      provider at that upstream and mounts this plugin;
//   3. assert the recorded request bodies carry `extra_headers[...]`, that the
//      value is stable across the run, and that a control run without the
//      plugin carries none.
//
// Run with: npm run test:e2e          (needs `dsh` on PATH)

import { spawn } from 'node:child_process'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { startMockUpstream } from './mock-upstream.mjs'

const pluginRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
const HEADER = 'x-opencode-session'
const TASK = 'Reply with the single word: pong'

/**
 * Compose the overlay that points a `gwds` pi-ai provider at the recording
 * upstream (and, for the plugin run, mounts this package beside the overlay).
 */
function overlayFor({ port, debugFile, plugin }) {
  return `# generated by tests/e2e/run.mjs — never shipped
- id: llm-pi-ai
  config:
    providers:
      gwds:
        apiKeyEnv: MOCK_API_KEY
        api: openai-completions
        baseURL: http://127.0.0.1:${port}/v1
        models:
          - id: mock-model
            name: Mock Model
            contextWindow: 200000
            maxTokens: 8192
- id: agent-default-model
  config:
    provider: gwds
    model: mock-model
${plugin ? `- insert:
    - id: litellm-extra-headers-e2e
      name: ./index.js
      config:
        providers: [gwds]
        hosts: ["127.0.0.1:${port}"]
        header: ${HEADER}
        mode: session-id
        debug: true
        debugFile: ${JSON.stringify(debugFile)}
` : ''}`
}

/** Boot one headless run and return its output once it exits. */
function runDsh({ overlayPath, timeoutMs = 180000 }) {
  const args = ['--profile', 'headless', '--patch', overlayPath, TASK]
  // `dsh` is a .cmd shim on Windows, which CreateProcess cannot execute
  // directly; run it through the command interpreter instead of `shell: true`
  // so the arguments stay individually escaped.
  const command = process.platform === 'win32' ? process.env.ComSpec ?? 'cmd.exe' : 'dsh'
  const commandArgs = process.platform === 'win32' ? ['/d', '/s', '/c', 'dsh', ...args] : args
  const child = spawn(command, commandArgs, {
    cwd: pluginRoot,
    env: { ...process.env, MOCK_API_KEY: 'sk-e2e-mock' },
    stdio: ['ignore', 'pipe', 'pipe'],
  })
  let stdout = ''
  let stderr = ''
  child.stdout.on('data', (chunk) => {
    stdout += chunk
  })
  child.stderr.on('data', (chunk) => {
    stderr += chunk
  })
  const timer = setTimeout(() => child.kill(), timeoutMs)
  return new Promise((resolveExit) => {
    child.on('close', (code) => {
      clearTimeout(timer)
      resolveExit({ code, stdout, stderr })
    })
  })
}

/** One full pass: upstream + overlay + dsh + the requests it recorded. */
async function runVariant({ label, plugin, debugFile }) {
  const upstream = await startMockUpstream()
  const overlayPath = join(pluginRoot, `.e2e.${label}.yml`)
  await writeFile(overlayPath, overlayFor({ port: upstream.port, debugFile, plugin }), 'utf8')
  try {
    const result = await runDsh({ overlayPath })
    return { label, debugFile, ...result, chat: upstream.chatRequests() }
  } finally {
    await upstream.close()
    await rm(overlayPath, { force: true })
  }
}

const headerValues = (chat) => chat.map((entry) => entry.json?.extra_headers?.[HEADER])

function describeRequests(label, chat) {
  console.log(`\n--- ${label}: ${chat.length} chat request(s) ---`)
  for (const entry of chat) {
    console.log(`  ${entry.method} ${entry.host}${entry.url} extra_headers=${JSON.stringify(entry.json?.extra_headers)}`)
  }
}

async function main() {
  const dir = await mkdtemp(join(tmpdir(), 'litellm-e2e-'))
  const failures = []
  const check = (ok, message) => {
    console.log(`${ok ? 'ok  ' : 'FAIL'} ${message}`)
    if (!ok) failures.push(message)
  }

  try {
    const pluginRun = await runVariant({
      label: 'plugin',
      plugin: true,
      debugFile: join(dir, 'debug.ndjson'),
    })
    const controlRun = await runVariant({
      label: 'control',
      plugin: false,
      debugFile: join(dir, 'debug-control.ndjson'),
    })

    describeRequests('with plugin', pluginRun.chat)
    describeRequests('control (no plugin row)', controlRun.chat)

    check(pluginRun.code === 0, `plugin run exits 0 (got ${pluginRun.code})`)
    check(pluginRun.chat.length >= 1, 'plugin run reached the recording upstream')

    const values = headerValues(pluginRun.chat)
    check(
      values.length > 0 && values.every((value) => typeof value === 'string' && value.length > 0),
      `every request carries ${HEADER} (got ${JSON.stringify(values)})`,
    )
    check(new Set(values).size === 1, `the value is stable across the run (got ${JSON.stringify(values)})`)

    check(controlRun.chat.length >= 1, 'control run reached the recording upstream')
    check(
      headerValues(controlRun.chat).every((value) => value === undefined),
      'the control run carries no extra_headers',
    )

    const debugLines = (await readFile(pluginRun.debugFile, 'utf8').catch(() => ''))
      .trim()
      .split('\n')
      .filter(Boolean)
    check(debugLines.length > 0, 'debugFile recorded at least one decision')
    for (const line of debugLines) {
      const record = JSON.parse(line)
      check(
        record.event === 'inject' && record.header === HEADER && record.value === values[0],
        `debug record is an inject for ${HEADER} (${line})`,
      )
    }

    if (pluginRun.stdout.trim().length > 0) console.log(`\nfinal text: ${pluginRun.stdout.trim()}`)
    if (failures.length > 0) {
      console.log(`\nplugin run stderr tail:\n${pluginRun.stderr.split('\n').slice(-20).join('\n')}`)
    }
  } finally {
    await rm(dir, { recursive: true, force: true })
  }

  if (failures.length > 0) {
    console.error(`\n${failures.length} check(s) failed`)
    process.exitCode = 1
  } else {
    console.log('\nall checks passed')
  }
}

await main()
